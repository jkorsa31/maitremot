/**
 * Builds MaitreMot's French dictionary files from Grammalecte's Hunspell
 * dictionary (npm package `dictionary-fr`, MPL-2.0).
 *
 *   npm run build:dictionary -w @maitremot/tools
 *
 * Steps:
 * 1. expand every stem of the .dic file into all its forms (hunspell.ts);
 * 2. keep only forms playable on the board: lowercase French letters only
 *    (no proper nouns, acronyms, digits, hyphens, apostrophes), 2 to 15 letters;
 * 3. write two DAWGs into packages/lexicon-fr/src/generated/:
 *    - words:   board words (A–Z, no accents) → used to validate moves and by the AI;
 *    - lexicon: "<spelling>=<lemma rule>" → used to fetch definitions.
 *
 * The output is committed, so the app and the server do not need this step.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  BOARD_SIZE,
  LEXICON_ALPHABET,
  LETTERS,
  SPELLING_CHARS,
  buildDawg,
  encodeLexiconEntry,
  normalizeWord,
} from '@maitremot/engine';
import { expandEntry, parseAffixFile } from './hunspell';

const here = dirname(fileURLToPath(import.meta.url));
const outputDir = join(here, '../../packages/lexicon-fr/src/generated');
const source = dirname(createRequire(import.meta.url).resolve('dictionary-fr'));

const spellingPattern = new RegExp(`^[${SPELLING_CHARS}]+$`, 'u');

async function main() {
  const [affText, dicText, sourcePackage] = await Promise.all([
    readFile(join(source, 'index.aff'), 'utf8'),
    readFile(join(source, 'index.dic'), 'utf8'),
    readFile(join(source, 'package.json'), 'utf8'),
  ]);
  const aff = parseAffixFile(affText);
  // Elisions ("l'", "qu'", "jusqu'"...) are useless on a board.
  const skipAffix = (rule: { add: string }) => /['’]/.test(rule.add);

  // 1–2. Expand and filter. Map: spelling → set of lemmas.
  const forms = new Map<string, Set<string>>();
  const lines = dicText.split('\n').slice(1); // first line = entry count
  for (const line of lines) {
    const entry = line.split(/\s/)[0];
    if (!entry) continue;
    const slash = entry.indexOf('/');
    const stem = slash < 0 ? entry : entry.slice(0, slash);
    const flags = slash < 0 ? '' : entry.slice(slash + 1);
    for (const { form, lemma } of expandEntry(aff, stem, flags, skipAffix)) {
      if (!spellingPattern.test(form)) continue;
      const length = normalizeWord(form).length;
      if (length < 2 || length > BOARD_SIZE) continue;
      let lemmas = forms.get(form);
      if (!lemmas) forms.set(form, (lemmas = new Set()));
      lemmas.add(lemma);
    }
  }

  // 3. Build the DAWGs.
  const boardWords = new Set([...forms.keys()].map(normalizeWord));
  const words = buildDawg(boardWords, LETTERS.join(''));
  const lexiconEntries: string[] = [];
  for (const [form, lemmas] of forms) {
    for (const lemma of lemmas) lexiconEntries.push(encodeLexiconEntry(form, lemma));
  }
  const lexicon = buildDawg(lexiconEntries, LEXICON_ALPHABET);

  await mkdir(outputDir, { recursive: true });
  const version = (JSON.parse(sourcePackage) as { version: string }).version;
  const header = (what: string) =>
    `// GENERATED by tools/dictionary/build.ts — do not edit by hand.\n` +
    `// ${what}\n` +
    `// Source: Grammalecte French dictionary (npm dictionary-fr@${version}), MPL-2.0.\n`;
  await writeFile(
    join(outputDir, 'words.ts'),
    `${header(`${boardWords.size} board words, DAWG of ${words.size} edges.`)}` +
      `export const WORDS_DAWG_BASE64 =\n  '${Buffer.from(words.toBytes()).toString('base64')}';\n`,
  );
  await writeFile(
    join(outputDir, 'lexicon.ts'),
    `${header(`${forms.size} spellings with lemmas, DAWG of ${lexicon.size} edges.`)}` +
      `export const LEXICON_DAWG_BASE64 =\n  '${Buffer.from(lexicon.toBytes()).toString('base64')}';\n`,
  );

  console.log(`Spellings: ${forms.size}`);
  console.log(`Board words: ${boardWords.size} → ${(words.size * 4) / 1e6} MB`);
  console.log(`Lexicon entries: ${lexiconEntries.length} → ${(lexicon.size * 4) / 1e6} MB`);
}

await main();
